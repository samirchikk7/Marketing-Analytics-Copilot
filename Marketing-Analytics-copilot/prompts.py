def marketing_insights_prompt(summary_text: str) -> str:
    return f"""
Ты — маркетинговый аналитик.

На основе данных:
- опиши общую картину эффективности каналов и кампаний;
- выдели 3–7 ключевых инсайтов (что хорошо, что плохо, где странности);
- предложи 3–5 конкретных действий (что отключить, что масштабировать, какие гипотезы и A/B-тесты поставить).

Формат ответа:
1. Общая картина
2. Ключевые инсайты (маркированный список)
3. Рекомендации по действиям (маркированный список)

Данные:
{summary_text}
"""


def marketing_ab_test_prompt(summary_text: str) -> str:
    return f"""
Ты — эксперт по A/B-тестированию и маркетинговой аналитике.

Тебе даётся сводка по топ/антитоп кампаниям и каналам: CTR, CPA, ROAS, расходы, каналы.

На основе этих данных нужно:

## 1. Определить ключевые проблемы
- где низкий ROAS → возможно, неправильный оффер, аудитория или посадочная страница;
- где высокий CPA → дорогие клики или плохое пост-клик поведение;
- где высокий CTR при низкой конверсии → проблемы с лендингом или несоответствие оффера.

## 2. Сформировать 5–10 A/B-гипотез.
Для каждой гипотезы обязательно укажи:
- **Сегмент / объект теста** (кампания, канал, креатив, аудитория)
- **Что меняем**
- **Метрика успеха** (CTR, CPS, CPA, ROAS, CR)
- **Ожидаемый эффект и почему**
- **Риски / ограничения**

## 3. Приоритизация
В конце сформируй блок:
### TOP-3 гипотез по Impact / Effort

Формат должен быть структурированным, аккуратным, с заголовками.

Данные:
{summary_text}
"""
